    <h1>Política de cookies</h1>
    <div class="legal-sub">Última actualización: <?= date('d/m/Y') ?></div>

    <p>
        Esta política describe el uso de cookies y tecnologías similares en la Plataforma BALTAE, en
        cumplimiento del artículo 22.2 de la <strong>Ley 34/2002 (LSSI-CE)</strong> y la
        <strong>Guía de cookies de la AEPD</strong>.
    </p>

    <h2>1. ¿Qué son las cookies?</h2>
    <p>
        Una cookie es un pequeño archivo que se descarga en tu dispositivo al acceder a determinadas
        páginas web. Permite al sitio recordar información sobre tu visita: preferencias, estado de
        sesión, etc.
    </p>

    <h2>2. ¿Qué cookies usamos?</h2>
    <p>
        BALTAE utiliza únicamente cookies <strong>técnicas estrictamente necesarias</strong> para el
        funcionamiento del servicio. <strong>No empleamos cookies analíticas, publicitarias ni de
        terceros</strong>, por lo que, conforme a la normativa, no se requiere consentimiento previo
        para su instalación.
    </p>

    <table>
        <thead>
            <tr><th>Cookie</th><th>Finalidad</th></tr>
        </thead>
        <tbody>
            <tr>
                <th><code>baltae_sid</code></th>
                <td>Cookie de sesión. Mantiene tu identificador de sesión entre páginas para que no tengas que iniciar sesión continuamente. Marcada como <code>HttpOnly</code>, <code>Secure</code> y <code>SameSite=Strict</code>. Se elimina al cerrar el navegador o tras cerrar sesión.</td>
            </tr>
        </tbody>
    </table>

    <p>
        Adicionalmente, almacenamos en el <strong>almacenamiento local del navegador</strong>
        (<code>localStorage</code>) una preferencia para recordar si tienes el menú lateral colapsado
        (<code>baltae_collapsed</code>). No se trata técnicamente de una cookie y no se envía al
        servidor.
    </p>

    <h2>3. Cookies de terceros</h2>
    <p>
        La Plataforma carga tipografías desde Google Fonts y, en las páginas con mapas, librerías de
        Leaflet/OpenStreetMap. Estos servicios pueden registrar tu dirección IP por motivos
        operativos. No utilizamos los servicios de tracking de Google ni instalamos cookies de
        terceros con fines publicitarios o analíticos.
    </p>

    <h2>4. Cómo gestionar las cookies</h2>
    <p>
        Puedes configurar tu navegador para aceptar, rechazar o eliminar las cookies en cualquier
        momento. Ten en cuenta que, al ser cookies estrictamente necesarias, su rechazo puede impedir
        el correcto funcionamiento del servicio (no podrás iniciar sesión).
    </p>
